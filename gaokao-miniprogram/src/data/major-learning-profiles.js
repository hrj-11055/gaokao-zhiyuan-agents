function cleanMajorName(name) {
  return String(name || '').trim().replace(/[（）()]/g, '')
}

function nonEmptyArray(value) {
  return Array.isArray(value) && value.length > 0
}

function isGenericCourseList(courses = []) {
  const joined = courses.map((item) => String(item || '')).join('、')
  return /通识基础|专业基础课|专业基础课程|专业核心课|专业核心课程|实践训练课|实践训练/.test(joined)
}

function isGenericAbilityList(abilities = []) {
  const joined = abilities.map((item) => String(item || '')).join('、')
  return /持续学习|信息检索|表达沟通|解决复杂问题/.test(joined)
}

function isGenericSummary(summary = '') {
  return /数据库暂未匹配|通用参考|建议结合目标院校最新培养方案/.test(String(summary || ''))
}

export function normalizeMajorName(name) {
  const raw = cleanMajorName(name)
  if (!raw) return ''
  const alias = OFFICIAL_MAJOR_ALIASES[raw] || raw
  if (MAJOR_LEARNING_PROFILES[alias]) return alias
  const rule = KEYWORD_PROFILE_RULES.find((item) => alias.includes(item.keyword))
  return rule?.major || alias
}

export function getMajorLearningProfile(name, backendInsight = null) {
  const officialName = normalizeMajorName(name)
  const curated = MAJOR_LEARNING_PROFILES[officialName] || DEFAULT_PROFILE
  const insight = backendInsight || {}
  const backendCourses = nonEmptyArray(insight.courses) && !isGenericCourseList(insight.courses)
    ? insight.courses
    : []
  const backendSummary = insight.summary && !isGenericSummary(insight.summary)
    ? insight.summary
    : ''
  const backendAbilities = nonEmptyArray(insight.abilities) && !isGenericAbilityList(insight.abilities)
    ? insight.abilities
    : []
  const backendSalary = insight.salarySummary && !/薪资受城市、院校层次/.test(insight.salarySummary)
    ? insight.salarySummary
    : ''

  return {
    name: officialName || cleanMajorName(name),
    summary: backendSummary || curated.summary,
    courses: backendCourses.length ? backendCourses : curated.courses,
    abilities: backendAbilities.length ? backendAbilities : curated.abilities,
    salarySummary: backendSalary || curated.salarySummary,
    source: backendSummary || backendCourses.length || backendSalary ? 'report-library' : 'curated',
  }
}

export function buildMajorCards(majorNames = [], insightMap = {}) {
  const seen = new Set()
  return majorNames
    .map((rawName) => {
      const name = normalizeMajorName(rawName)
      if (!name || seen.has(name)) return null
      seen.add(name)
      return {
        name,
        originalName: cleanMajorName(rawName),
        insight: getMajorLearningProfile(name, insightMap[name] || insightMap[rawName]),
      }
    })
    .filter(Boolean)
}
