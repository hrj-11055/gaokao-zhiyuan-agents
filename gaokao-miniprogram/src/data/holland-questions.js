/**
 * 霍兰德类型简称映射
 */
export const HOLLAND_TYPE_LABELS = {
  R: '现实型',
  I: '研究型',
  A: '艺术型',
  S: '社会型',
  E: '企业型',
  C: '常规型'
}

/**
 * 计算霍兰德职业兴趣代码
 * @param {Object} answers - 答案对象，格式为 { questionId: optionIndex }
 *                          其中 questionId 是题目 ID (1-60)，optionIndex 是选项索引 (0-3)
 * @returns {Object} { code: 'RIA', scores: { R: 35, I: 32, A: 28, S: 25, E: 20, C: 18 } }
 */
export function calculateHollandCode(answers) {
  // 初始化各类型分数
  const scores = {
    R: 0,
    I: 0,
    A: 0,
    S: 0,
    E: 0,
    C: 0
  }

  // 计算每个类型的总分
  // 答案索引0-3对应分数1-4 (索引+1)
  HOLLAND_QUESTIONS.forEach(q => {
    const answer = answers[q.id]
    if (answer !== undefined && answer >= 0 && answer <= 3) {
      scores[q.type] += (answer + 1)
    }
  })

  // 按分数降序排序，获取前三名
  const sortedTypes = Object.entries(scores)
    .sort((a, b) => b[1] - a[1])
    .slice(0, 3)
    .map(entry => entry[0])

  // 生成三字母代码
  const code = sortedTypes.join('')

  return {
    code,
    scores
  }
}

/**
 * 根据代码获取类型描述
 * @param {string} code - 霍兰德代码（如 'RIA'）
 * @returns {Object} 类型描述对象
 */
export function getHollandDescription(code) {
  // 如果精确匹配三字母代码
  if (HOLLAND_TYPE_DESCRIPTIONS[code]) {
    return HOLLAND_TYPE_DESCRIPTIONS[code]
  }

  // 如果没有精确匹配，使用前两个字母匹配
  const twoLetterCode = code.substring(0, 2)
  for (const [key, value] of Object.entries(HOLLAND_TYPE_DESCRIPTIONS)) {
    if (key.startsWith(twoLetterCode)) {
      return value
    }
  }

  // 如果还是没有匹配，使用第一个字母作为主类型
  const primaryType = code[0]
  const primaryLabel = HOLLAND_TYPE_LABELS[primaryType] || '未知'

  return {
    name: `${primaryLabel}为主型`,
    tags: [primaryLabel],
    traits: [`以${primaryLabel}为主的职业兴趣类型`],
    careers: ['请完成完整测试获取详细推荐'],
    majors: ['请完成完整测试获取详细推荐']
  }
}

/**
 * 获取用户的霍兰德类型详细报告
 * @param {string} code - 霍兰德代码
 * @param {Object} scores - 各类型分数
 * @returns {Object} 详细报告
 */
export function getHollandReport(code, scores) {
  const description = getHollandDescription(code)

  // 获取排序后的类型列表
  const sortedTypes = Object.entries(scores)
    .sort((a, b) => b[1] - a[1])
    .map(([type, score]) => ({
      type,
      label: HOLLAND_TYPE_LABELS[type],
      score
    }))

  return {
    code,
    description,
    scores,
    sortedTypes,
    dominant: sortedTypes[0],
    secondary: sortedTypes[1],
    tertiary: sortedTypes[2]
  }
}
